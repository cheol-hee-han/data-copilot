def generate_biz_manual_data() -> list[dict]:
    """500+ 업무 매뉴얼 데이터 생성."""
    data = []
    for category, domain, topics in _BIZ_TOPICS:
        for title, content in topics:
            data.append({
                "title": title,
                "category": category,
                "domain": domain,
                "content": content,
            })

    # 추가 변형 생성 (목표 500+)
    base_count = len(data)
    if base_count < 500:
        extras_needed = 500 - base_count
        for i in range(extras_needed):
            src = data[i % base_count]
            # 세부 사항 변형
            suffixes = [
                " 이 절차는 분기별로 점검하며, 변경 사항은 즉시 반영한다.",
                " 관련 규정은 은행업감독규정 및 내부 규정집에서 확인할 수 있다.",
                " 예외 사항이 발생하면 담당 부서장의 승인을 받아 처리한다.",
                " 실적은 월별로 집계하여 경영진에 보고한다.",
                " 준법감시 부서의 사전 검토를 받아야 한다.",
                " 고객에게 사전 안내 후 처리하며, 안내 이력을 기록한다.",
                " 위반 시 내부 징계 및 외부 제재 대상이 될 수 있다.",
            ]
            data.append({
                "title": f"{src['title']} (세부)",
                "category": src["category"],
                "domain": src["domain"],
                "content": src["content"] + random.choice(suffixes),
            })
    return data


